import fs from "node:fs";

/** Replaces (or appends) one section of docs/eval-results.md between markers, so each eval script owns its part. */
export function writeEvalSection(name: string, markdown: string, file = "docs/eval-results.md") {
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  const block = `${start}\n${markdown.trim()}\n${end}`;
  let doc = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "# Eval results\n\nGenerated by the eval scripts; re-run them to refresh.\n";
  if (doc.includes(start) && doc.includes(end)) doc = doc.slice(0, doc.indexOf(start)) + block + doc.slice(doc.indexOf(end) + end.length);
  else doc = `${doc.trimEnd()}\n\n${block}\n`;
  fs.writeFileSync(file, doc);
}
